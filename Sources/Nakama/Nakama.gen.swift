enum ApiRequests {

    /// Add friends by ID or username to a user's account.
    static func NakamaAddFriends(
        ids: [String] = [],
        usernames: [String] = []
    ) -> ApiRequest<EmptyResponse> {
        let path = "/v2/friend"

        var queryItems = [URLQueryItem]()
        for value in ids {
            queryItems.append(URLQueryItem(name: "ids", value: "\(value)"))
        }
        for value in usernames {
            queryItems.append(URLQueryItem(name: "usernames", value: "\(value)"))
        }

        return ApiRequest(
            method: .post,
            path: path,
            queryItems: queryItems,
            body: nil
        )
    }

    /// Add users to a group.
    static func NakamaAddGroupUsers(
        groupId: String,
        userIds: [String] = []
    ) -> ApiRequest<EmptyResponse> {
        var path = "/v2/group/{group_id}/add"
